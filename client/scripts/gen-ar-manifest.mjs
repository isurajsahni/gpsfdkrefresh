/**
 * Generates src/data/arManifest.generated.js from the AR catalog.
 *
 *   npm run gen:ar-manifest                        # from the live catalog
 *   npm run gen:ar-manifest -- path/to/catalog.json  # from a local build
 *
 * Why a manifest at all: the product page has to know, before the shopper
 * taps, whether this artwork has a model in the size they picked. The catalog
 * itself is ~280 KB and lives on another origin — fetching it on every product
 * page is exactly the regression that got AR removed in Sep 2026. All the page
 * actually needs is slug -> available size labels, which interns down to about
 * 1.5 KB gzipped. The full catalog is still fetched, but only on iOS and only
 * once a shopper is launching AR, where the .usdz filename is needed.
 *
 * Run this whenever the AR catalog changes. The manifest is a second source of
 * truth, and a stale one hides buttons that should show.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/data/arManifest.generated.js');
const LIVE = 'https://ar-sage-eight.vercel.app/models/catalog.json';

const source = process.argv[2] || LIVE;

async function load(src) {
  if (/^https?:/.test(src)) {
    const r = await fetch(src);
    if (!r.ok) throw new Error(`${src} -> ${r.status}`);
    return r.json();
  }
  return JSON.parse(await readFile(resolve(process.cwd(), src), 'utf8'));
}

const { artworks = [] } = await load(source);

// Most artworks share the same handful of size sets, so intern them: the
// manifest stores each distinct set once and points slugs at it by index.
const families = [];
const keyOf = new Map();
const slugs = {};

for (const art of artworks) {
  const fam = {};
  for (const p of art.products ?? []) {
    fam[p.id] = (p.sizes ?? []).map((s) => s.label);
  }
  // Sorted key so two identically-shaped families always intern together.
  const key = JSON.stringify(Object.keys(fam).sort().map((k) => [k, fam[k]]));
  let i = keyOf.get(key);
  if (i === undefined) {
    i = families.length;
    keyOf.set(key, i);
    families.push(fam);
  }
  slugs[art.id] = i;
}

const body = `// GENERATED by scripts/gen-ar-manifest.mjs — do not edit by hand.
// Source: ${source}
// Regenerate whenever the AR catalog changes: npm run gen:ar-manifest

export const GENERATED_AT = '${new Date().toISOString().slice(0, 10)}';

/** Distinct size sets, interned. */
export const FAMILIES = ${JSON.stringify(families, null, 2)};

/** Product slug -> index into FAMILIES. */
export const SLUGS = ${JSON.stringify(slugs, null, 2)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, 'utf8');

const sizes = families.reduce((n, f) => n + Object.values(f).flat().length, 0);
console.log(
  `${artworks.length} artworks -> ${families.length} families, ${sizes} labels\n` +
  `wrote ${OUT} (${(body.length / 1024).toFixed(1)} KB raw)`
);
